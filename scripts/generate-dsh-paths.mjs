/**
 * Generate tsconfig.dsh-paths.json from the sibling DSH checkout's
 * tsconfig.base.json paths — the single source of truth for repo-local
 * resolution. Vendored packages resolve to their built type declarations so
 * `skipLibCheck` absorbs their relaxed-strictness sources; harness packages
 * resolve to source.
 *
 * Run automatically before typecheck and tests; re-run after DSH package
 * layout changes.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** tsc rejects bare relative paths entries without baseUrl; force a './' prefix. */
function withDotSlash(path) {
  const normalized = path.split(String.fromCharCode(92)).join('/')
  return normalized.startsWith('.') ? normalized : `./${normalized}`
}
// The sibling DSH checkout; CI checks it out into the workspace and points
// DSH_CHECKOUT_DIR at it.
const checkoutDir = resolve(projectRoot, process.env.DSH_CHECKOUT_DIR ?? '../deepseek-harness')
const baseTsconfig = resolve(checkoutDir, 'tsconfig.base.json')

/** Strip // and /* *​/ comments from a tsconfig JSON body. */
function stripJsonComments(text) {
  let out = ''
  let index = 0
  let inString = false
  while (index < text.length) {
    const char = text[index]
    if (inString) {
      out += char
      if (char === '\\') {
        out += text[index + 1] ?? ''
        index += 2
        continue
      }
      if (char === '"') inString = false
      index += 1
      continue
    }
    if (char === '"') {
      inString = true
      out += char
      index += 1
      continue
    }
    if (char === '/' && text[index + 1] === '/') {
      while (index < text.length && text[index] !== '\n') index += 1
      continue
    }
    if (char === '/' && text[index + 1] === '*') {
      index += 2
      while (index < text.length && !(text[index] === '*' && text[index + 1] === '/')) index += 1
      index += 2
      continue
    }
    out += char
    index += 1
  }
  return out
}

/** Map one vendored `src` target to its built declaration file, when built. */
function vendorDeclarationTarget(absoluteTarget) {
  const segments = absoluteTarget.split(/[/\\]/)
  const vendorIndex = segments.indexOf('vendor')
  if (vendorIndex === -1) return undefined
  const vendorName = segments[vendorIndex + 1]
  if (vendorName === undefined) return undefined
  const declaration = join(checkoutDir, 'vendor', vendorName, 'lib', 'types', 'index.d.ts')
  return existsSync(declaration) ? declaration : undefined
}

const base = JSON.parse(stripJsonComments(readFileSync(baseTsconfig, 'utf8')))
const paths = base.compilerOptions?.paths
if (paths === undefined) {
  throw new Error(`no compilerOptions.paths in ${baseTsconfig}`)
}

const resolvedPaths = {}
for (const [key, targets] of Object.entries(paths)) {
  const target = targets[0]
  if (target === undefined) continue
  const absolute = resolve(checkoutDir, target)
  const declaration = vendorDeclarationTarget(absolute)
  // Paths entries resolve relative to the file that carries them, so rewrite
  // every target relative to this project root.
  const mapped = declaration ?? absolute
  resolvedPaths[key] = [withDotSlash(relative(projectRoot, mapped))]
}

writeFileSync(
  resolve(projectRoot, 'tsconfig.dsh-paths.json'),
  `${JSON.stringify({
    _comment: 'Generated by scripts/generate-dsh-paths.mjs — do not edit.',
    extends: `${process.env.DSH_CHECKOUT_DIR ?? '../deepseek-harness'}/tsconfig.base.json`,
    compilerOptions: { paths: resolvedPaths },
  }, null, 2)}\n`,
)
console.log(`generated tsconfig.dsh-paths.json from ${baseTsconfig} (${Object.keys(resolvedPaths).length} paths)`)

/**
 * Generate tsconfig.build-paths.json for compiling `lib/`: every
 * @deepseek-ai package resolves to its built type declarations in the
 * sibling DSH checkout (found by scanning package manifests), so the build
 * program contains only this package's sources — no checkout sources are
 * emitted, and emitted declarations reference the same bare package names
 * the host resolves at runtime.
 *
 * Run automatically before build; re-run after DSH package layout changes.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { dirname } from 'node:path'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** tsc rejects bare relative paths entries without baseUrl; force a './' prefix. */
function withDotSlash(path) {
  const normalized = path.split(String.fromCharCode(92)).join('/')
  return normalized.startsWith('.') ? normalized : `./${normalized}`
}
// The sibling DSH checkout; CI checks it out into the workspace and points
// DSH_CHECKOUT_DIR at it.
const checkoutDir = resolve(projectRoot, process.env.DSH_CHECKOUT_DIR ?? '../deepseek-harness')

// `node generate-dsh-build-paths.mjs [compat]` — default scans the checkout;
// `compat` scans the npm-installed public-line packages under compat/.
const compatMode = process.argv[2] === 'compat'
const outputName = compatMode ? 'tsconfig.compat-paths.json' : 'tsconfig.build-paths.json'
const compatScopeDir = resolve(projectRoot, 'compat/node_modules/@deepseek-ai')

/** Package roots to scan for `name` -> directory mappings. */
function* packageDirs() {
  if (compatMode) {
    // pnpm materializes these entries as junctions/symlinks, which report as
    // non-directories on some platforms — filter by manifest presence instead.
    for (const entry of readdirSync(compatScopeDir)) {
      const dir = join(compatScopeDir, entry)
      if (existsSync(join(dir, 'package.json'))) yield dir
    }
    return
  }
  for (const vendor of ['cordis', 'cosmokit', 'schemastery', 'loader', 'include', 'group', 'timer', 'hmr', 'logger-console']) {
    yield join(checkoutDir, 'vendor', vendor)
  }
  const packages = join(checkoutDir, 'packages')
  for (const group of readdirSync(packages, { withFileTypes: true })) {
    if (!group.isDirectory()) continue
    const groupDir = join(packages, group.name)
    for (const pkg of readdirSync(groupDir, { withFileTypes: true })) {
      if (!pkg.isDirectory()) continue
      yield join(groupDir, pkg.name)
    }
  }
}

/** Map one package's `exports` subpaths to built declaration files. */
function declarationPaths(name, dir) {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  if (manifest.name !== name || manifest.exports === undefined) return {}
  const out = {}
  for (const [subpath, target] of Object.entries(manifest.exports)) {
    if (subpath === './package.json') continue
    const types = typeof target === 'string' ? target : target?.types
    if (typeof types !== 'string' || !types.endsWith('.d.ts')) continue
    if (!existsSync(resolve(dir, types))) {
      if (compatMode) throw new Error(`compat package ${name}: exported types ${types} missing — run pnpm --dir compat install`)
      continue
    }
    if (subpath === '.') {
      out[name] = [withDotSlash(relative(projectRoot, resolve(dir, types)))]
    } else {
      const suffix = `/${subpath.replace(/^\.\//, '')}`
      out[`${name}${suffix}`] = [withDotSlash(relative(projectRoot, resolve(dir, types)))]
    }
  }
  return out
}

const paths = {}
for (const dir of packageDirs()) {
  const manifestPath = join(dir, 'package.json')
  if (!existsSync(manifestPath)) continue
  const name = JSON.parse(readFileSync(manifestPath, 'utf8')).name
  if (typeof name !== 'string' || !name.startsWith('@deepseek-ai/')) continue
  Object.assign(paths, declarationPaths(name, dir))
}

// The runtime closure under the dsh home is the fallback for packages the
// checkout scan missed (none expected today; a miss fails the build loudly).
void homedir

writeFileSync(
  resolve(projectRoot, outputName),
  `${JSON.stringify({
    _comment: compatMode
      ? 'Generated by scripts/generate-dsh-build-paths.mjs compat — do not edit.'
      : 'Generated by scripts/generate-dsh-build-paths.mjs — do not edit.',
    extends: compatMode ? './tsconfig.flags.json' : `${process.env.DSH_CHECKOUT_DIR ?? '../deepseek-harness'}/tsconfig.base.json`,
    compilerOptions: { paths },
  }, null, 2)}\n`,
)
console.log(`generated ${outputName} (${Object.keys(paths).length} entries)`)
